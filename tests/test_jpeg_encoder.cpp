constexpr std::array<unsigned char, 192> make_rgb_samples()
{
    std::array<unsigned char, 192> result{};
    for (std::size_t y = 0; y < 8; ++y) {
        for (std::size_t x = 0; x < 8; ++x) {
            std::size_t const offset = (y * 8 + x) * 3;
            result[offset] = static_cast<unsigned char>(x * 32);
            result[offset + 1] = static_cast<unsigned char>(y * 32);
            result[offset + 2] = static_cast<unsigned char>((x + y) * 16);
        }
    }
    return result;
}


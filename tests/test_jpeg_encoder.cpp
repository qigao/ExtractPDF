int failures = 0;

void check(bool condition, char const* message)
{
    if (!condition) {
        std::fprintf(stderr, "FAIL: %s\n", message);
        ++failures;
    }
}

std::vector<unsigned char> const& golden_for(int components, int quality)
{
    if (components == 1) {
        if (quality == 40) {
            return golden_gray_q40;
        }
        if (quality == 90) {
            return golden_gray_q90;
        }
        return golden_gray_q100;
    }
    if (quality == 40) {
        return golden_rgb_q40;
    }
    if (quality == 90) {
        return golden_rgb_q90;
    }
    return golden_rgb_q100;
}

bool encode_once(
    quantapdf::detail::jpeg_image_spec const& spec,
    unsigned char const* samples,
    std::size_t sample_size,
    std::vector<unsigned char>& output)
{
    Pl_Buffer sink("quantapdf-jpeg-test");
    std::unique_ptr<quantapdf::detail::jpeg_encoder> encoder;
    if (quantapdf::detail::jpeg_encoder::create(spec, &sink, &encoder) !=
        QUANTAPDF_OK) {
        return false;
    }
    encoder->pipeline()->write(samples, sample_size);
    encoder->pipeline()->finish();
    std::unique_ptr<Buffer> const buffer(sink.getBuffer());
    output.assign(buffer->getBuffer(), buffer->getBuffer() + buffer->getSize());
    return true;
}

bool is_complete_jpeg(std::vector<unsigned char> const& encoded)
{
    return encoded.size() >= 4 && encoded[0] == 0xff && encoded[1] == 0xd8 &&
        encoded[encoded.size() - 2] == 0xff && encoded.back() == 0xd9;
}

void test_valid_encoding()
{
    for (int quality: {40, 90, 100}) {
        for (int components: {1, 3}) {
            unsigned char const* samples = components == 1
                ? gray_samples.data()
                : rgb_samples.data();
            std::size_t const sample_size = components == 1
                ? gray_samples.size()
                : rgb_samples.size();
            quantapdf::detail::jpeg_image_spec const spec{
                8, 8, components, quality};
            std::vector<unsigned char> first;
            std::vector<unsigned char> second;
            check(
                encode_once(spec, samples, sample_size, first),
                "fixed JPEG encoding succeeds");
            check(
                encode_once(spec, samples, sample_size, second),
                "repeated fixed JPEG encoding succeeds");
            check(is_complete_jpeg(first), "output has complete JPEG markers");
            check(first == second, "repeated fixed JPEG bytes are identical");
            check(
                first == golden_for(components, quality),
                "complete JPEG bytes match the checked golden array");
        }
    }

    std::vector<unsigned char> q40;
    std::vector<unsigned char> q90;
    std::vector<unsigned char> q100;
    check(
        encode_once({8, 8, 1, 40}, gray_samples.data(), gray_samples.size(), q40),
        "quality 40 encoding succeeds");
    check(
        encode_once({8, 8, 1, 90}, gray_samples.data(), gray_samples.size(), q90),
        "quality 90 encoding succeeds");
    check(
        encode_once(
            {8, 8, 1, 100}, gray_samples.data(), gray_samples.size(), q100),
        "quality 100 encoding succeeds");
    check(q40 != q90, "quality 40 and 90 bytes differ");
    check(is_complete_jpeg(q100), "quality 100 still emits JPEG");
}

void test_factory_validation()
{
    Pl_Buffer sink("quantapdf-jpeg-validation");
    std::unique_ptr<quantapdf::detail::jpeg_encoder> encoder;
    auto const expect = [&](quantapdf::detail::jpeg_image_spec spec,
                            Pipeline* next,
                            quantapdf_status expected,
                            char const* message) {
        quantapdf_status const status =
            quantapdf::detail::jpeg_encoder::create(spec, next, &encoder);
        check(status == expected, message);
        check(!encoder, "factory failure clears output encoder");
    };

    check(
        quantapdf::detail::jpeg_encoder::create(
            {8, 8, 1, 90}, &sink, nullptr) == QUANTAPDF_ERROR_ARGUMENT,
        "null output holder is rejected");
    expect({8, 8, 1, 90}, nullptr, QUANTAPDF_ERROR_ARGUMENT,
           "null downstream pipeline is rejected");
    expect({0, 8, 1, 90}, &sink, QUANTAPDF_ERROR_ARGUMENT,
           "zero width is rejected");
    expect({8, 0, 1, 90}, &sink, QUANTAPDF_ERROR_ARGUMENT,
           "zero height is rejected");
    expect({8, 8, 2, 90}, &sink, QUANTAPDF_ERROR_ARGUMENT,
           "two components are rejected");
    expect({8, 8, 4, 90}, &sink, QUANTAPDF_ERROR_ARGUMENT,
           "four components are rejected");
    expect({8, 8, 1, 0}, &sink, QUANTAPDF_ERROR_ARGUMENT,
           "quality zero is rejected");
    expect({8, 8, 1, 101}, &sink, QUANTAPDF_ERROR_ARGUMENT,
           "quality above 100 is rejected");

    std::size_t const jdimension_max =
        static_cast<std::size_t>(std::numeric_limits<JDIMENSION>::max());
    if (jdimension_max < std::numeric_limits<std::size_t>::max()) {
        expect(
            {jdimension_max + 1, 1, 1, 90},
            &sink,
            QUANTAPDF_ERROR_FORMAT,
            "width above JDIMENSION is rejected");
    }
    expect(
        {jdimension_max, jdimension_max, 3, 90},
        &sink,
        QUANTAPDF_ERROR_FORMAT,
        "sample-size multiplication overflow is rejected");

    check(
        quantapdf::detail::jpeg_encoder::create(
            {8, 8, 1, 90}, &sink, &encoder) == QUANTAPDF_OK &&
            encoder != nullptr,
        "valid factory call publishes an encoder");
    check(
        quantapdf::detail::jpeg_encoder::create(
            {8, 8, 1, 0}, &sink, &encoder) == QUANTAPDF_ERROR_ARGUMENT &&
            encoder == nullptr,
        "factory failure clears a previously published encoder");
}

void test_wrong_sample_size()
{
    for (std::size_t size: {gray_samples.size() - 1, gray_samples.size() + 1}) {
        bool threw = false;
        try {
            Pl_Buffer sink("quantapdf-jpeg-wrong-size");
            std::unique_ptr<quantapdf::detail::jpeg_encoder> encoder;
            if (quantapdf::detail::jpeg_encoder::create(
                    {8, 8, 1, 90}, &sink, &encoder) == QUANTAPDF_OK) {
                std::array<unsigned char, 65> samples{};
                encoder->pipeline()->write(samples.data(), size);
                encoder->pipeline()->finish();
            }
        } catch (std::runtime_error const&) {
            threw = true;
        }
        check(threw, "wrong sample size raises a codec runtime error");
    }
}

